  static List<String> requiredForRole(String role) {
    final normalized = role.toLowerCase();
    for (final entry in _roleMap.entries) {
      if (normalized.contains(entry.key)) return entry.value;
    }
    if (normalized.contains('engineer') || normalized.contains('developer')) {
      return _roleMap['software engineer']!;
    }
    if (normalized.contains('analyst') || normalized.contains('scientist')) {
      return _roleMap['data']!;
    }
    if (normalized.contains('manager')) return _roleMap['project manager']!;
    return _roleMap['general']!;
  }

  static List<String> extractSkills(String text) {
    final lower = text.toLowerCase();
    final found = <String>[];
    for (final skill in allSkills) {
      final pattern = RegExp(
        r'(?<![a-z0-9])' + RegExp.escape(skill) + r'(?![a-z0-9])',
        caseSensitive: false,
      );
      if (pattern.hasMatch(lower)) found.add(skill);
    }
    return found;
  }

  static List<String> displayNames(Iterable<String> skills) {
    return skills.map((skill) {
      return skill
          .split(' ')
          .map((word) {
            if (word.isEmpty) return word;
            if (word.length <= 3 &&
                word.toLowerCase() != 'aws' &&
                word != 'gcp') {
              return word.toUpperCase();
            }
            return '${word[0].toUpperCase()}${word.substring(1)}';
          })
          .join(' ');
    }).toList();
  }

